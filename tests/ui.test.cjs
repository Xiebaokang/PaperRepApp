const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { _electron: electron } = require('@playwright/test');
const { Library } = require('../electron/library.cjs');

test('desktop UI: navigation, import, debounced scoped search, multi-select, delete, settings and sorting', { timeout: 90000 }, async t => {
  const base = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'paperrep-ui-')));
  const root = path.join(base, 'papers'), userData = path.join(base, 'user-data');
  await fs.mkdir(root); await fs.mkdir(userData);
  await fs.mkdir('test-results', { recursive: true });
  const lib = new Library(path.join(userData, 'library.json'), async () => {});
  await lib.init(); await lib.configure({ root, remote: '' });
  const env = { ...process.env, PAPERREP_USER_DATA: userData };
  // On Windows an empty value still enables Electron's Node mode.
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: ['.'], cwd: path.join(__dirname, '..'), env });
  t.after(async () => {
    const closed = app.waitForEvent('close');
    await app.evaluate(({ app }) => app.exit(0)).catch(() => {});
    await closed;
    await fs.rm(base, { recursive: true, force: true });
  });
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('#busy-overlay', { state: 'hidden' });
  await page.screenshot({ path: 'test-results/empty.png' });
  const names = ['Attention Is All You Need', 'Retrieval-Augmented Generation', 'Learning Transferable Visual Models', 'Scaling Laws for Neural Language Models', 'Deep Residual Learning', 'Denoising Diffusion Probabilistic Models'];
  const sources = [];
  for (const name of names) { const file = path.join(base, name + '.pdf'); await fs.writeFile(file, '%PDF-1.7\n\0test fixture\n%%EOF'); sources.push(file); }
  await page.evaluate(async files => { const result = await window.paperrep.invoke('import', { files, month: '2026/11' }); if (result.error) throw new Error(result.error); }, sources);
  await page.locator('.file-row').filter({ hasText: '2026' }).dblclick();
  await page.waitForSelector('.file-row[data-id="2026/11"]');
  await page.locator('.file-row[data-id="2026/11"]').dblclick();
  await page.waitForSelector('.file-row[data-kind="paper"]');
  assert.equal(await page.locator('.file-row').count(), 6);
  await page.screenshot({ path: 'test-results/library.png' });
  await app.evaluate(({ shell }) => { shell.openPath = async target => { globalThis.openedPdf = target; return ''; }; });
  await page.locator('.file-row').first().dblclick();
  assert.match(await app.evaluate(() => globalThis.openedPdf), /Attention Is All You Need\.pdf$/);
  const snapshot = await page.evaluate(async () => (await window.paperrep.invoke('state')).data);
  await app.evaluate(({ BrowserWindow }, snapshot) => BrowserWindow.getAllWindows()[0].webContents.send('library-state', { ...snapshot, busy: true, phase: '同步 GitHub' }), snapshot);
  await page.waitForSelector('#busy-overlay[open]');
  assert.equal(await page.locator('#app').evaluate(el => el.inert), true);
  await page.keyboard.press('Escape'); assert.equal(await page.locator('#busy-overlay').isVisible(), true);
  await app.evaluate(({ BrowserWindow }, snapshot) => BrowserWindow.getAllWindows()[0].webContents.send('library-state', snapshot), snapshot);
  await page.waitForSelector('#busy-overlay', { state: 'hidden' });
  await page.locator('#search').fill('Attention');
  await page.waitForTimeout(600); assert.equal(await page.locator('.file-row').count(), 6);
  await page.waitForTimeout(550); assert.equal(await page.locator('.file-row').count(), 1);
  await page.locator('#search').fill('Learning');
  await page.waitForTimeout(1150); assert.equal(await page.locator('.file-row').count(), 2);
  await page.locator('#nav-folders').click();
  await page.locator('#search').fill('Attention'); await page.waitForTimeout(1150);
  assert.equal(await page.locator('.file-row').count(), 0);
  assert.match(await page.locator('#empty-description').textContent(), /进入月份或切换到所有论文后搜索/);
  await page.locator('#nav-all').click(); assert.equal(await page.locator('.file-row').count(), 6);
  await page.locator('#sort-direction').click();
  assert.match(await page.locator('.file-row').first().textContent(), /Scaling Laws/);
  const a = page.locator('.file-row').nth(0), b = page.locator('.file-row').nth(1);
  await a.click(); await b.click({ modifiers: [process.platform === 'darwin' ? 'Meta' : 'Control'] });
  assert.equal(await page.locator('.file-row.selected').count(), 2);
  await b.click({ button: 'right' });
  assert.equal(await page.locator('#context-menu').isVisible(), true);
  await app.evaluate(({ dialog, shell }) => { dialog.showMessageBox = async () => ({ response: 1 }); shell.trashItem = async target => { process.getBuiltinModule('fs').rmSync(target, { recursive: true }); }; });
  await page.locator('#context-delete').click();
  await page.waitForFunction(() => document.querySelectorAll('.file-row').length === 4);
  await page.locator('#nav-folders').click();
  await page.locator('#new-folder').click();
  await page.locator('#month-input').fill('2025-03');
  await page.locator('#month-submit').click();
  await page.waitForSelector('#month-dialog', { state: 'hidden' });
  assert.equal(await page.locator('.file-row').count(), 2);
  const newSource = path.join(base, 'Imported via button.pdf'); await fs.writeFile(newSource, '%PDF-1.7\nfixture\n%%EOF');
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, newSource);
  await page.locator('#add-button').click(); await page.waitForSelector('#busy-overlay', { state: 'hidden' });
  await page.waitForFunction(() => document.getElementById('stat-papers').textContent.includes('5'));
  await assert.rejects(fs.access(newSource));
  await page.locator('#settings-button').click();
  assert.match(await page.locator('#root-label').textContent(), /papers/);
  await page.screenshot({ path: 'test-results/settings.png' });
  await page.locator('#settings-dialog .close-dialog').first().click();
  const rowCount = await page.locator('.file-row').count();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  assert.deepEqual(await app.evaluate(({ BrowserWindow }) => {
    const windows = BrowserWindow.getAllWindows();
    return { count: windows.length, visible: windows[0].isVisible() };
  }), { count: 1, visible: false });
  await app.evaluate(({ app }) => app.emit('activate'));
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
  assert.equal(await page.locator('.file-row').count(), rowCount);
  assert.deepEqual(errors, []);
});
